using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Oathlord.Shared.Blacksmith.Anvil;
using Content.Oathlord.Shared.Blacksmith.Anvil.Prototypes;
using Content.Shared.Storage;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Containers;

namespace Content.Oathlord.Client.Blacksmith.Anvil;

[GenerateTypedNameReferences]
public sealed partial class AnvilWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _proto = default!;
    [Dependency] private IEntityManager _entMan = default!;
    private SharedContainerSystem _container;

    private EntityQuery<AnvilComponent> _anvilQuery;

    public AnvilRecipesWindow? RecipesWindow;

    private EntityUid _owner;

    public AnvilWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _container = _entMan.System<SharedContainerSystem>();
        _anvilQuery = _entMan.GetEntityQuery<AnvilComponent>();

        OutputsButton.OnPressed += OutputsButtonOnOnPressed;
    }

    private void OutputsButtonOnOnPressed(BaseButton.ButtonEventArgs obj)
    {
        if (!_container.TryGetContainer(_owner, StorageComponent.ContainerId, out var container))
            return;

        RecipesWindow?.Close();
        RecipesWindow = new AnvilRecipesWindow();
        RecipesWindow.SetupWindow(container.ContainedEntities);
        RecipesWindow.OnClose += () => RecipesWindow = null;

        RecipesWindow.OpenCentered();
    }

    public override void Close()
    {
        base.Close();
        RecipesWindow?.Close();
    }

    public void SetOwner(EntityUid owner)
    {
        _owner = owner;
    }

    public void UpdateWindow()
    {
        if (!_anvilQuery.TryComp(_owner, out var anvilComponent) || !_container.TryGetContainer(_owner, StorageComponent.ContainerId, out var container))
            return;

        UpdateViewsContainer(container.ContainedEntities, anvilComponent.AllowedWorkables);
        UpdateRecipe(anvilComponent.SelectedRecipe);
    }

    public void UpdateViewsContainer(NetEntity metal)
    {
        foreach (var child in ViewsContainer.Children)
        {
            if (child is not WorkableMetalView view)
                continue;

            view.SetupView(metal);
        }
    }

    public void UpdateViewsContainer(IReadOnlyList<EntityUid> entities, int amount)
    {
        ViewsContainer.Children.Clear();
        for (var i = 0; i < amount; i++)
        {
            var metalView = new WorkableMetalView();
            var element = entities.ElementAtOrDefault(i);
            metalView.SetupView(element);

            ViewsContainer.AddChild(metalView);
        }
    }

    public void UpdateRecipe(ProtoId<AnvilRecipePrototype>? recipe)
    {
        if (recipe is not { } anvilRecipe|| !_proto.TryIndex(anvilRecipe, out var recipeProto))
        {
            RecipeName.Text = "No recipe has been selected...";
            return;
        }

        RecipeName.Text = recipeProto.Result.ToString();
        WorkRequired.Text = recipeProto.WorkRequired.ToString();
    }
}

